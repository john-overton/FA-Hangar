#!/usr/bin/env python3
"""Generate crates/hangar-app/src/ui_glyphs.rs: icon masks and UI text advances.

    python3 fa-hangar-design/tools/gen/glyphs.py

Needs rsvg-convert and ImageMagick `magick` for the icons, and Liberation Sans
(Regular and Bold TTF) for the advance tables. Nothing here runs in the app:
the output is plain integer const data, so the app never parses SVG or fonts.
"""
import os
import re
import struct
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
DESIGN = os.path.normpath(os.path.join(HERE, "..", ".."))
REPO = os.path.normpath(os.path.join(DESIGN, ".."))
OUT = os.path.join(REPO, "crates", "hangar-app", "src", "ui_glyphs.rs")
ICONS = os.path.join(DESIGN, "icons")
FONT_DIRS = ["/usr/share/fonts/liberation", "/usr/share/fonts/truetype/liberation", "/usr/share/fonts/TTF"]

# Coverage thresholds (0..255) for the two-level icon masks.
FULL = 166  # >= 65%: drawn in the icon color
HALF = 77  # >= 30%: drawn in the icon color mixed halfway into the background


def find_font(name):
    for d in FONT_DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    out = subprocess.run(["fc-match", "-f", "%{file}", name.replace(".ttf", "").replace("-", ":style=")],
                         capture_output=True, text=True).stdout
    if out and os.path.exists(out):
        return out
    raise SystemExit(f"Font not found: {name}")


def advances(path):
    """Advance widths of ASCII 32..126 in 1/64 em, from the TTF hmtx and cmap tables."""
    data = open(path, "rb").read()
    tables = {}
    count = struct.unpack_from(">H", data, 4)[0]
    for i in range(count):
        tag, _, offset, length = struct.unpack_from(">4sIII", data, 12 + i * 16)
        tables[tag.decode()] = (offset, length)
    units = struct.unpack_from(">H", data, tables["head"][0] + 18)[0]
    metrics = struct.unpack_from(">H", data, tables["hhea"][0] + 34)[0]
    hmtx = tables["hmtx"][0]
    cmap = tables["cmap"][0]
    sub = None
    for i in range(struct.unpack_from(">H", data, cmap + 2)[0]):
        platform, encoding, offset = struct.unpack_from(">HHI", data, cmap + 4 + i * 8)
        if platform == 3 and encoding == 1:
            sub = cmap + offset
    if sub is None or struct.unpack_from(">H", data, sub)[0] != 4:
        raise SystemExit("Expected a format 4 Unicode cmap")
    segs = struct.unpack_from(">H", data, sub + 6)[0] // 2
    ends = struct.unpack_from(f">{segs}H", data, sub + 14)
    starts = struct.unpack_from(f">{segs}H", data, sub + 16 + segs * 2)
    deltas = struct.unpack_from(f">{segs}h", data, sub + 16 + segs * 4)
    range_at = sub + 16 + segs * 6
    ranges = struct.unpack_from(f">{segs}H", data, range_at)

    def glyph(ch):
        for i in range(segs):
            if starts[i] <= ch <= ends[i]:
                if ranges[i] == 0:
                    return (ch + deltas[i]) & 0xFFFF
                at = range_at + i * 2 + ranges[i] + (ch - starts[i]) * 2
                g = struct.unpack_from(">H", data, at)[0]
                return (g + deltas[i]) & 0xFFFF if g else 0
        return 0

    out = []
    for ch in range(32, 127):
        g = min(glyph(ch), metrics - 1)
        adv = struct.unpack_from(">H", data, hmtx + g * 4)[0]
        out.append((adv * 64 + units // 2) // units)
    return out


def camel(name):
    return "".join(p.capitalize() for p in name.split("-"))


def coverage(svg, size):
    png = subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), svg], capture_output=True, check=True).stdout
    raw = subprocess.run(["magick", "png:-", "-alpha", "extract", "-depth", "8", "gray:-"],
                         input=png, capture_output=True, check=True).stdout
    if len(raw) != size * size:
        raise SystemExit(f"Unexpected raster size for {svg}")
    return raw


def runs(raw, size, lo, hi):
    """Horizontal runs (row, x, len) of pixels with lo <= coverage < hi."""
    out = []
    for y in range(size):
        x = 0
        while x < size:
            if lo <= raw[y * size + x] < hi:
                end = x
                while end < size and lo <= raw[y * size + end] < hi:
                    end += 1
                out.append((y, x, end - x))
                x = end
            else:
                x += 1
    return out


def main():
    names = sorted(f[:-4] for f in os.listdir(ICONS) if f.endswith(".svg"))
    regular = advances(find_font("LiberationSans-Regular.ttf"))
    bold = advances(find_font("LiberationSans-Bold.ttf"))
    lines = [
        "//! Generated by fa-hangar-design/tools/gen/glyphs.py. Do not edit by hand.",
        "//! Icons: each fa-hangar-design/icons/*.svg rasterized once at 16 and 12 px and",
        f"//! thresholded into full (coverage >= {FULL}/255) and half (>= {HALF}/255) pixel",
        "//! runs `(row, x, len)`. Full runs take the icon color; half runs take the icon",
        "//! color mixed halfway into the background, so edges stay solid GDI fills.",
        "//! Advances: Liberation Sans (Arial/Tahoma-class metrics) widths of ASCII 32..126",
        "//! in 1/64 em, used to estimate proportional UI text width on every backend.",
        "",
        "/// Proportional UI font advance widths, ASCII 32..126, 1/64 em.",
        f"pub const UI_ADVANCE: [u8; 95] = {regular};",
        "/// Bold (weight 600+) UI font advance widths, ASCII 32..126, 1/64 em.",
        f"pub const UI_ADVANCE_BOLD: [u8; 95] = {bold};",
        "",
        "/// One generated 16px icon per fa-hangar-design/icons/*.svg file.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum Glyph {",
    ]
    lines += [f"    {camel(n)}," for n in names]
    lines += [
        "}",
        "",
        "/// Two-level coverage mask: runs of `(row, x, len)` on the icon's square grid.",
        "pub struct Mask {",
        "    pub full: &'static [(u8, u8, u8)],",
        "    pub half: &'static [(u8, u8, u8)],",
        "}",
        "",
        "impl Glyph {",
        f"    pub const ALL: [Glyph; {len(names)}] = [",
    ]
    lines += [f"        Glyph::{camel(n)}," for n in names]
    lines += [
        "    ];",
        "    /// The source SVG's file stem, also the icon's accessible title.",
        "    pub const fn name(self) -> &'static str {",
        "        match self {",
    ]
    lines += [f'            Glyph::{camel(n)} => "{n}",' for n in names]
    lines += ["        }", "    }", "    /// The 16px mask, or the 12px one (`th-ic-sm`) when `small`.",
              "    pub const fn mask(self, small: bool) -> &'static Mask {", "        match (self, small) {"]
    for n in names:
        lines.append(f"            (Glyph::{camel(n)}, false) => &{camel(n).upper()},")
        lines.append(f"            (Glyph::{camel(n)}, true) => &{camel(n).upper()}_SM,")
    lines += ["        }", "    }", "}", ""]
    fmt = lambda rs: "[" + ", ".join(f"({y}, {x}, {w})" for y, x, w in rs) + "]"
    for n in names:
        for size, suffix in ((16, ""), (12, "_SM")):
            raw = coverage(os.path.join(ICONS, n + ".svg"), size)
            lines.append(f"const {camel(n).upper()}{suffix}: Mask = Mask {{")
            lines.append(f"    full: &{fmt(runs(raw, size, FULL, 256))},")
            lines.append(f"    half: &{fmt(runs(raw, size, HALF, FULL))},")
            lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT, REPO)}: {len(names)} icons")


if __name__ == "__main__":
    main()
